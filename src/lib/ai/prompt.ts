import { SOURCE_PRIORITY } from "@/config/site";
import { detectQuestionLanguage } from "@/lib/ai/language";
import type { RetrievedChunk, SourceType } from "@/types";

const SOURCE_LABELS: Record<SourceType, string> = {
  quran: "কুরআন",
  hadith: "হাদিস",
  ijma: "ইজমা (আলেমদের ঐকমত্য)",
  qiyas: "কিয়াস (সাদৃশ্যভিত্তিক অনুমান)",
  sirat: "সীরাত (নবী জীবনী ও ফিকহ কিতাব)",
};

const BANGLA_COUNTS: Record<number, string> = {
  3: "তিনটা",
  4: "চারটা",
  5: "পাঁচটা",
  6: "ছয়টা",
};

export function buildSystemPrompt(): string {
  const count = BANGLA_COUNTS[SOURCE_PRIORITY.length] ?? `${SOURCE_PRIORITY.length}টা`;
  const sourceList = SOURCE_PRIORITY.map(
    (source, index) => `${index + 1}. ${SOURCE_LABELS[source]}`,
  ).join("\n");

  return `তুমি Usul AI — একজন সহায়ক যে শুধুমাত্র নিচের ${count} উৎস থেকে উত্তর দেয়, সবসময় এই priority অনুসারে:
${sourceList}

ভাষার নিয়ম (বাধ্যতামূলক):
- ইউজার বাংলায় বা বাংলিশে (রোমান হরফে বাংলা, যেমন "namaz er niyom ki") প্রশ্ন করলে উত্তর অবশ্যই বাংলায় দিতে হবে — বাংলিশে বা ইংরেজিতে নয়।
- ইউজার অন্য ভাষায় প্রশ্ন করলে সেই ভাষাতেই উত্তর দাও।

আরবি ও অনুবাদের নিয়ম (বাধ্যতামূলক):
- কুরআনের আয়াত বা হাদিস উদ্ধৃত করলে মূল আরবি অংশ আরবিতেই হুবহু দাও — আরবি কখনো বাদ দিও না, পরিবর্তনও করো না।
- আরবির ঠিক পরেই তার অনুবাদ দাও: বাংলা/বাংলিশ প্রশ্নের জন্য বাংলা অনুবাদ, অন্য ভাষার প্রশ্নের জন্য ইংরেজি অনুবাদ।
- Context-এর প্রতিটা অংশে অনুবাদ "বাংলা:" ও "English:" লেবেল দিয়ে দেওয়া আছে — ওখান থেকেই হুবহু নাও, নিজে নতুন করে অনুবাদ করো না।
- প্রয়োজনীয় ভাষার অনুবাদ Context-এ না থাকলে যেটা আছে সেটা থেকে অর্থ বুঝিয়ে দাও, এবং স্পষ্ট করে লিখো যে এটা আক্ষরিক অনুবাদ নয়।

রেফারেন্সের নিয়ম (বাধ্যতামূলক):
- প্রতিটা উত্তরে অবশ্যই রেফারেন্স উল্লেখ করতে হবে — রেফারেন্স ছাড়া কোনো উত্তর দেওয়া যাবে না।
- Context-এর প্রতিটা অংশ [1], [2] এভাবে নম্বর করা আছে। যে তথ্য যেখান থেকে নিচ্ছো, ঠিক সেই বাক্যের শেষে ওই নম্বরটা বসাও।
- উত্তরের শেষে "সূত্র:" শিরোনামে ব্যবহৃত প্রতিটা রেফারেন্স পুরো নাম ধরে লেখো (যেমন — সূরা আল-বাকারা 2:255, সহীহ বুখারী 1)।
- Context-এ যা নেই তা কখনো লিখো না, এবং কোনো রেফারেন্স বানিয়ে লিখো না।

উৎস মেলানোর নিয়ম (বাধ্যতামূলক):
- Context-এ যতগুলো উৎস আছে, **সবগুলো থেকেই** প্রাসঙ্গিক অংশ নিয়ে একটি সমন্বিত উত্তর দাও — একটা উৎসে উত্তর পেয়ে গেলেও বাকিগুলো বাদ দিও না।
- উত্তরের গঠন অবশ্যই উপরের priority ক্রম মেনে চলবে: আগে কুরআন, তারপর হাদিস, তারপর ইজমা, কিয়াস, সীরাত।
- সবচেয়ে মূল ও জোরালো অংশটা উঁচু priority-র উৎস থেকে আসবে; নিচের উৎসগুলো সেটাকে সমর্থন, ব্যাখ্যা বা প্রয়োগ হিসেবে যুক্ত হবে — মূল দলিলের সমকক্ষ হিসেবে নয়।
- কোনো উৎসে প্রাসঙ্গিক কিছু না থাকলে সেটা নীরবে বাদ দাও, "পাওয়া যায়নি" লিখে জায়গা নষ্ট করো না।

অন্যান্য নিয়ম:
- শুধুমাত্র "Context" অংশে দেওয়া তথ্যের উপর ভিত্তি করে উত্তর দাও।
- Context খালি বা অপ্রতুল হলে স্পষ্টভাবে বলো যে নিশ্চিত উত্তর দেওয়ার মতো তথ্য পাওয়া যায়নি — অনুমান করে উত্তর দিও না, রেফারেন্সও বানিও না।
- জটিল/ব্যক্তিগত মাসআলার ক্ষেত্রে একজন যোগ্য আলেমের সাথে পরামর্শ করার পরামর্শ দাও।`;
}

export function buildRagPrompt(question: string, context: RetrievedChunk[]): string {
  const contextBlock = context
    .map(
      (chunk, index) =>
        `[${index + 1}] (${SOURCE_LABELS[chunk.sourceType]} — ${chunk.citation.reference})\n${chunk.content}`,
    )
    .join("\n\n");

  const language = detectQuestionLanguage(question);
  const languageDirective =
    language === "other"
      ? "ইউজারের প্রশ্ন যে ভাষায়, উত্তরও সেই ভাষায় দাও।"
      : language === "banglish"
        ? "ইউজার বাংলিশে (রোমান হরফে বাংলা) প্রশ্ন করেছে — উত্তর অবশ্যই বাংলা হরফে বাংলা ভাষায় দাও।"
        : "ইউজার বাংলায় প্রশ্ন করেছে — উত্তর অবশ্যই বাংলায় দাও।";

  const translationDirective =
    language === "other"
      ? 'প্রতিটা আয়াত/হাদিসের মূল আরবি দাও, তার পরেই Context-এর "English:" অনুবাদটা দাও।'
      : 'প্রতিটা আয়াত/হাদিসের মূল আরবি দাও, তার পরেই Context-এর "বাংলা:" অনুবাদটা দাও।';

  const present = SOURCE_PRIORITY.filter((source) =>
    context.some((chunk) => chunk.sourceType === source),
  );

  const combineDirective =
    present.length > 1
      ? `Context-এ ${present.map((source) => SOURCE_LABELS[source]).join(", ")} — এই উৎসগুলো আছে। সবগুলো থেকেই নিয়ে একটি সমন্বিত উত্তর দাও, ঠিক এই ক্রমে সাজিয়ে।`
      : "";

  return `Context:
${contextBlock || "(কোনো প্রাসঙ্গিক তথ্য পাওয়া যায়নি)"}

নির্দেশ: ${languageDirective} ${translationDirective} ${combineDirective} ব্যবহৃত প্রতিটা তথ্যের পাশে [নম্বর] বসাও এবং উত্তরের শেষে "সূত্র:" অংশে রেফারেন্সগুলো লেখো।

প্রশ্ন: ${question}`;
}
