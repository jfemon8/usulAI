function noteBlock(chunk: RetrievedChunk): string {
  return chunk.note
    ? `\n\nতাফসীরি অনুবাদ ও টীকা (${QURANENC_CONFIG.translator}, QuranEnc.com): ${chunk.note}`
    : "";
}

function translationLabel(chunk: RetrievedChunk): string {
  return chunk.machineTranslated ? ", বাংলা ও English অনুবাদ: AI অনুবাদ" : "";
}

function bookPartLabel(chunk: RetrievedChunk): string {
  if (chunk.sourceType !== "fiqh") return "";
  const book = OPENITI_CONFIG.fiqh.find(({ title }) => chunk.citation.reference.startsWith(title));
  return book?.part ? `, ধরন: ${book.part}` : "";
}

function gradeLabel(chunk: RetrievedChunk): string {
  const described = describeGrades(chunk.grades);
  return described ? `, মান: ${described}` : "";
}
